create extension if not exists pg_trgm;

create table if not exists public.provinces (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name_km text not null,
  name_en text not null,
  banner_image_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.places (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  province_id bigint not null references public.provinces(id) on delete restrict,
  listing_type text not null default 'attraction' check (listing_type in ('attraction','accommodation','restaurant')),
  business_type text check (business_type in ('hotel','guest_house','restaurant','cafe','other')),
  publication_status text not null default 'draft' check (publication_status in ('draft','published','paused')),
  category text not null check (category in ('history','nature','beach','adventure','culture','food')),
  name_km text not null,
  name_en text not null,
  summary_km text,
  summary_en text,
  image_url text,
  ticket_usd numeric(6,2),
  ticket_status text check (ticket_status in ('free','unknown','check')),
  ticket_url text,
  ticket_provider text,
  open_hours text,
  access_km text,
  access_en text,
  source_urls jsonb not null default '[]'::jsonb,
  lat numeric(9,6),
  lng numeric(9,6),
  views bigint not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.province_guides (
  id bigint generated by default as identity primary key,
  province_id bigint not null unique references public.provinces(id) on delete cascade,
  overview_km text not null,
  overview_en text not null,
  story_km text,
  story_en text,
  history_km text,
  history_en text,
  culture_km text,
  culture_en text,
  travel_km text,
  travel_en text,
  attractions_km text not null,
  attractions_en text not null,
  stay_guide_km text not null,
  stay_guide_en text not null,
  food_guide_km text not null,
  food_guide_en text not null,
  source_urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.place_guides (
  id bigint generated by default as identity primary key,
  place_id bigint not null unique references public.places(id) on delete cascade,
  about_km text,
  about_en text,
  history_km text,
  history_en text,
  highlights_km text,
  highlights_en text,
  visit_plan_km text,
  visit_plan_en text,
  tips_km text,
  tips_en text,
  source_urls jsonb not null default '[]'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_places_province_status_type
  on public.places (province_id, publication_status, listing_type);

create index if not exists idx_places_category
  on public.places (category);

create index if not exists idx_places_views
  on public.places (views desc);

create index if not exists idx_places_name_en_trgm
  on public.places using gin (name_en gin_trgm_ops);

create index if not exists idx_places_name_km_trgm
  on public.places using gin (name_km gin_trgm_ops);

create index if not exists idx_provinces_name_en
  on public.provinces (name_en);

alter table public.provinces enable row level security;
alter table public.places enable row level security;
alter table public.province_guides enable row level security;
alter table public.place_guides enable row level security;

drop policy if exists "public can read provinces" on public.provinces;
create policy "public can read provinces"
  on public.provinces
  for select
  to anon, authenticated
  using (true);

drop policy if exists "public can read published places" on public.places;
create policy "public can read published places"
  on public.places
  for select
  to anon, authenticated
  using (publication_status = 'published');

drop policy if exists "public can read province guides" on public.province_guides;
create policy "public can read province guides"
  on public.province_guides
  for select
  to anon, authenticated
  using (true);

drop policy if exists "public can read published place guides" on public.place_guides;
create policy "public can read published place guides"
  on public.place_guides
  for select
  to anon, authenticated
  using (
    exists (
      select 1
      from public.places p
      where p.id = place_guides.place_id
        and p.publication_status = 'published'
    )
  );

grant select on public.provinces to anon, authenticated;
grant select on public.places to anon, authenticated;
grant select on public.province_guides to anon, authenticated;
grant select on public.place_guides to anon, authenticated;
