create table if not exists public.admin_users (
  user_id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null,
  role text not null default 'editor' check (role in ('super_admin','admin','editor')),
  is_active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.admin_audit_log (
  id bigint generated by default as identity primary key,
  admin_user_id uuid references auth.users(id) on delete set null,
  entity_type text not null,
  entity_id bigint,
  action text not null,
  changed_fields jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists idx_admin_users_active_role on public.admin_users(is_active, role);
create index if not exists idx_admin_audit_created on public.admin_audit_log(created_at desc);
create index if not exists idx_admin_audit_entity on public.admin_audit_log(entity_type, entity_id);

alter table public.admin_users enable row level security;
alter table public.admin_audit_log enable row level security;

create schema if not exists private;

create or replace function private.is_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and is_active = true and role in ('super_admin','admin')
  );
$$;

create or replace function private.is_editor_or_admin()
returns boolean language sql stable security definer set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = auth.uid() and is_active = true and role in ('super_admin','admin','editor')
  );
$$;

revoke all on function private.is_admin() from public;
revoke all on function private.is_editor_or_admin() from public;
grant execute on function private.is_admin() to authenticated;
grant execute on function private.is_editor_or_admin() to authenticated;

drop policy if exists "admin users can read own record" on public.admin_users;
create policy "admin users can read own record" on public.admin_users
for select to authenticated using (user_id = auth.uid());

drop policy if exists "admins can read admin users" on public.admin_users;
create policy "admins can read admin users" on public.admin_users
for select to authenticated using ((select private.is_admin()));

drop policy if exists "admin editors can read audit log" on public.admin_audit_log;
create policy "admin editors can read audit log" on public.admin_audit_log
for select to authenticated using ((select private.is_editor_or_admin()));

drop policy if exists "admins can write audit log" on public.admin_audit_log;
create policy "admins can write audit log" on public.admin_audit_log
for insert to authenticated with check (admin_user_id = auth.uid());

drop policy if exists "admins can manage places" on public.places;
create policy "admins can manage places" on public.places for all to authenticated
using ((select private.is_editor_or_admin())) with check ((select private.is_editor_or_admin()));

drop policy if exists "admins can manage provinces" on public.provinces;
create policy "admins can manage provinces" on public.provinces for all to authenticated
using ((select private.is_editor_or_admin())) with check ((select private.is_editor_or_admin()));

drop policy if exists "admins can manage province guides" on public.province_guides;
create policy "admins can manage province guides" on public.province_guides for all to authenticated
using ((select private.is_editor_or_admin())) with check ((select private.is_editor_or_admin()));

drop policy if exists "admins can manage place guides" on public.place_guides;
create policy "admins can manage place guides" on public.place_guides for all to authenticated
using ((select private.is_editor_or_admin())) with check ((select private.is_editor_or_admin()));

grant select on public.admin_users to authenticated;
grant select, insert on public.admin_audit_log to authenticated;
grant select, insert, update, delete on public.places to authenticated;
grant select, insert, update, delete on public.provinces to authenticated;
grant select, insert, update, delete on public.province_guides to authenticated;
grant select, insert, update, delete on public.place_guides to authenticated;
